"""Demo mode: a one-tap demo account with a simulated patient (always labelled "simulated").

The persona is generated by ``happygut_engine.simulate`` with known, injected patterns
(high-fat meals, late nights and exam periods raise symptoms; spice and lactose don't), so
what the Pattern Finder shows in the demo can be checked against the truth. Dates are
relative to today: the history ends yesterday, and tonight's diary is still to fill in.

Everything lives in the in-memory store and is rebuilt on every start.
"""

from __future__ import annotations

import secrets
import time
from datetime import date, datetime, timedelta
from datetime import time as clock

import jwt

from happygut_engine import Component, Diagnosis, DiseaseState, Level
from happygut_engine.simulate import Effect, MenuItem, SimConfig, SimDay, StressPeriod, simulate

from .agents import AgentRun, PerceivedItem, Perception
from .auth import AuthError
from .diary import DiaryFood, DiaryIn, Sleep, Stool, StressPeriodOut, build_entry
from .flow import MealCheckFlow
from .insights import Insights
from .knowledge import MemoryKnowledge
from .store import MemoryStore, Patient

DEMO_USER = "demo-nusrat"
DEMO_PATIENT = "demo-patient-nusrat"
DAYS = 120

_MEALS = {
    "bread": ("morning",), "egg": ("morning",), "drink": ("morning",),
    "staple": ("noon", "evening"), "dal": ("noon", "evening"), "curry": ("noon", "evening"),
    "fish": ("noon", "evening"), "vegetable": ("noon", "evening"), "bhorta": ("noon",), "stew": ("noon", "evening"),
    "rice_dish": ("noon", "evening"), "dairy": ("noon",), "street_food": ("evening",), "snack": ("evening",),
    "sweet": ("evening",), "sweet_snack": ("evening",),
}
_WEIGHTS = {"staple": 3.0, "dal": 2.0, "vegetable": 1.5, "fish": 1.5, "curry": 1.2, "stew": 1.2, "bread": 1.5,
            "egg": 1.0, "drink": 1.0}


class DemoVerifier:
    """Signs and checks demo tokens with a key that lives only in this process."""

    def __init__(self) -> None:
        self._key = secrets.token_urlsafe(32)

    def issue(self, user_id: str = DEMO_USER, ttl_s: int = 12 * 3600) -> str:
        return jwt.encode({"sub": user_id, "aud": "demo", "exp": int(time.time()) + ttl_s}, self._key, algorithm="HS256")

    def user_id(self, token: str) -> str:
        try:
            return str(jwt.decode(token, self._key, algorithms=["HS256"], audience="demo")["sub"])
        except jwt.PyJWTError as exc:
            raise AuthError(type(exc).__name__) from None


class ScriptedPerceiver:
    """Seeds past meal checks through the real flow: the "perception" is the simulated meal itself."""

    def __init__(self) -> None:
        self.items: list[str] = []

    async def perceive(self, *, text, image, lang):
        return AgentRun(Perception(is_food=True, items=[PerceivedItem(name_en=n, confidence=0.95) for n in self.items]),
                        "simulated", "simulated")


class NoExplainer:
    async def explain(self, *, packet, lang, diagnosis):
        raise RuntimeError("seeded meal checks use the template explanation")


def build_menu(knowledge: MemoryKnowledge) -> list[MenuItem]:
    menu = []
    for dish in knowledge.graph.dishes.values():
        category = dish.raw.get("category", "")
        meals = _MEALS.get(category)
        if not meals:
            continue
        comps = {c: lvl for c, lvl in dish.components.items() if lvl is not None}
        rich = comps.get(Component.FAT, Level.NONE) >= Level.HIGH
        menu.append(MenuItem(dish.id, comps, frozenset(meals), _WEIGHTS.get(category, 0.5), rich))
    return menu


def persona_config(menu: list[MenuItem]) -> SimConfig:
    names = {m.name for m in menu}
    kacchi = "dish.kacchi_biryani" if "dish.kacchi_biryani" in names else next((m.name for m in menu if m.rich), None)
    forced = {d: (kacchi,) for d in (77, 80, 118)} if kacchi else {}
    return SimConfig(
        days=DAYS, seed=27,
        flare_windows=((41, 53), (83, 92)),
        food_effects={Component.FAT: Effect(2.4, 0.8)},
        late_night_effect=Effect(1.9, 0.75),
        period_effects={"exam": Effect(1.1, 0.7, next_day=0.0)},
        stress_periods=(StressPeriod("exam", "Mid-term exams", 34, 48), StressPeriod("family", "Cousin's wedding week", 76, 81)),
        forced_late_nights=frozenset({76, 78, 81, 117, 119}),
        forced_missed_doses=frozenset({118}),
        forced_foods=forced,
        calm_days=frozenset(range(70, 76)) | frozenset(range(100, 116)),
    )


def _entry(sim: SimDay, knowledge: MemoryKnowledge) -> DiaryIn:
    foods = []
    for f in sim.foods:
        en, bn = knowledge.names(f.name)
        foods.append(DiaryFood(name=en, name_bn=bn, dish_id=f.name, time_of_day=f.time_of_day, reactions=list(f.reactions)))
    i = sim.items
    return DiaryIn(
        foods=foods,
        stool=Stool(count=i.stools, night_count=i.night_stools, bristol=i.bristol, blood=i.blood, urgency=i.urgency),
        pain=i.pain, wellbeing=i.wellbeing, medication=sim.medication,
        sleep=Sleep(bedtime=sim.bedtime, wake_time=sim.wake_time, quality=sim.sleep_quality), stress=sim.stress,
    )


async def seed_demo(store: MemoryStore, knowledge: MemoryKnowledge, insights: Insights, flow: MealCheckFlow) -> Patient:
    """Fill the in-memory store with the simulated persona. Safe to call once at start-up."""
    patient = Patient(DEMO_PATIENT, Diagnosis.CD, DiseaseState.REMISSION, frozenset(), "bn", is_synthetic=True,
                      display_name="Nusrat")
    store.patients[DEMO_USER] = patient
    menu = build_menu(knowledge)
    today = insights.today()
    first = today - timedelta(days=DAYS)  # offset 0; offset DAYS-1 is yesterday
    if not menu:
        return patient
    config = persona_config(menu)
    sims = simulate(config, menu)

    bedtimes: list[str] = []
    for sim in sims:
        if not sim.logged:
            continue
        day = first + timedelta(days=sim.offset)
        completed = datetime.combine(day, clock(22, 40), tzinfo=insights.tz)
        entry = build_entry(_entry(sim, knowledge), day, patient.diagnosis, completed, day, bedtimes, True, "")
        await store.save_diary(patient.id, entry)
        bedtimes.append(sim.bedtime)

    for p in config.stress_periods:
        await store.add_stress_period(patient.id, StressPeriodOut(
            id=f"demo-{p.type}-{p.start}", type=p.type, name=p.name,
            start=first + timedelta(days=p.start), end=first + timedelta(days=p.end)))
    await store.add_stress_period(patient.id, StressPeriodOut(
        id="demo-exam-upcoming", type="exam", name="Final exams",
        start=today + timedelta(days=3), end=today + timedelta(days=16)))

    # The persona confirmed her past flares.
    decisions = await store.period_decisions(patient.id)
    periods = await insights.periods(patient)
    decisions.confirmed |= {date.fromisoformat(p["start"]) for p in periods["periods"] if p["kind"] == "flare"}
    await store.save_period_decisions(patient.id, decisions)

    # Past meal checks for the last few days, made by the real flow (engine verdict, template explanation).
    perceiver = ScriptedPerceiver()
    seeder = MealCheckFlow(knowledge, perceiver, NoExplainer(), flow.scrubber, store, personal=insights.personal_evidence)
    for sim in sims[-6:]:
        day = first + timedelta(days=sim.offset)
        entry = await store.get_diary(patient.id, day)
        if entry is None:
            continue
        for meal, hour in (("noon", 13), ("evening", 20)):
            foods = [f for f in entry.foods if f.time_of_day == meal]
            if not foods:
                continue
            perceiver.items = [f.name for f in foods]
            meal_check_id = None
            async for event in seeder.stream(patient, "en", None, None):
                if event.name == "done":
                    meal_check_id = event.data["meal_check_id"]
            if meal_check_id is None:
                continue
            store.meal_checks[meal_check_id].created_at = datetime.combine(day, clock(hour, 20), tzinfo=insights.tz)
            store.meal_checks[meal_check_id].input_type = "photo" if meal == "evening" else "text"
            for f in foods:
                f.source, f.meal_check_id = "meal_check", meal_check_id
    await insights.personal_evidence(patient)  # warm the cache
    return patient
