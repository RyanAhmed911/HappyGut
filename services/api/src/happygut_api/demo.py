class DemoVerifier:
    """Signs and checks session tokens. With no SESSION_SECRET the key lives only in this process."""

    def __init__(self, secret: str = "") -> None:
        self._key = secret or secrets.token_urlsafe(32)

    def issue(self, user_id: str, ttl_s: int = 12 * 3600) -> str:
        return jwt.encode({"sub": user_id, "aud": "happygut", "exp": int(time.time()) + ttl_s}, self._key, algorithm="HS256")

    def user_id(self, token: str) -> str:
        try:
            return str(jwt.decode(token, self._key, algorithms=["HS256"], audience="happygut")["sub"])
        except jwt.PyJWTError as exc:
            raise AuthError(type(exc).__name__) from None


@dataclass(frozen=True)
class Persona:
    """A test account: who signs in, and which sample patient they get."""

    key: str
    email: str
    role: str  # shown in the start-up log and the docs, for the portal's "test credentials" rows
    name: str
    diagnosis: Diagnosis
    phenotypes: frozenset[str] = frozenset()
    history: str | None = None  # which sample history to generate; None = a new patient with no records

    @property
    def user_id(self) -> str:
        return f"account-{self.key}"

    @property
    def patient_id(self) -> str:
        return f"patient-{self.key}"


PERSONAS = (
    Persona("nusrat", "nusrat@happygut.test", "Patient: Crohn's disease, in remission, 4 months of records", "Nusrat", Diagnosis.CD, history="cd_remission"),
    Persona("rafi", "rafi@happygut.test", "Patient: ulcerative colitis, in a flare, 4 months of records", "Rafi", Diagnosis.UC, history="uc_flare"),
    Persona("ayesha", "ayesha@happygut.test", "New patient: Crohn's disease with a stricture, no records yet", "Ayesha", Diagnosis.CD,
            frozenset({"stricturing"})),
)


class TestAccounts:
    """Sign-in for the test accounts. Passwords come from the environment (TEST_PASSWORD_<NAME>);
    an account without one gets a random password for this run, printed in the start-up log."""

    __test__ = False  # not a pytest class
    MAX_FAILURES, WINDOW_S = 8, 300

    def __init__(self, passwords: dict[str, str]):
        self.generated: dict[str, str] = {}
        self._passwords: dict[str, str] = {}
        for p in PERSONAS:
            password = passwords.get(p.key, "")
            if not password:
                password = self.generated[p.email] = secrets.token_urlsafe(9)
            self._passwords[p.email] = password
        self._failures: dict[str, list[float]] = {}

    def locked(self, email: str) -> bool:
        recent = [t for t in self._failures.get(email, []) if time.time() - t < self.WINDOW_S]
        self._failures[email] = recent
        return len(recent) >= self.MAX_FAILURES

    def check(self, email: str, password: str) -> Persona | None:
        """The persona for a correct email and password, else None (and the failure is counted)."""
        email = email.strip().lower()
        expected = self._passwords.get(email)
        # Compare even for an unknown email, so timing doesn't reveal which emails exist.
        ok = hmac.compare_digest((expected or secrets.token_urlsafe(9)).encode(), password.encode()) and expected is not None
        if not ok:
            self._failures.setdefault(email, []).append(time.time())
            return None
        self._failures.pop(email, None)
        return next(p for p in PERSONAS if p.email == email)


class ScriptedPerceiver:
    """Seeds past meal checks through the real flow: the "perception" is the simulated meal itself."""

    def __init__(self) -> None:
        self.items: list[str] = []

    async def perceive(self, *, text, image, lang):
        return AgentRun(Perception(is_food=True, items=[PerceivedItem(name_en=n, confidence=0.95) for n in self.items]),
                        "simulated", "simulated")


class NoExplainer:
    async def explain(self, *, packet, lang, diagnosis):
        raise RuntimeError("seeded meal checks use the template explanation")


def build_menu(knowledge: MemoryKnowledge) -> list[MenuItem]:
    menu = []
    for dish in knowledge.graph.dishes.values():
        category = dish.raw.get("category", "")
        meals = _MEALS.get(category)
        if not meals:
            continue
        comps = {c: lvl for c, lvl in dish.components.items() if lvl is not None}
        rich = comps.get(Component.FAT, Level.NONE) >= Level.HIGH
        menu.append(MenuItem(dish.id, comps, frozenset(meals), _WEIGHTS.get(category, 0.5), rich))
    return menu


def _config(history: str, menu: list[MenuItem]) -> tuple[SimConfig, list[tuple[str, str, int, int]]]:
    """(simulation settings, upcoming stressful periods as (type, name, days from today, length))."""
    names = {m.name for m in menu}
    if history == "uc_flare":
        # Ulcerative colitis: very spicy food and high-stress days raise symptoms; a flare began 8 days ago
        # after a work deadline.
        return SimConfig(
            days=DAYS, seed=41, flare_load=7.0,
            flare_windows=((30, 43), (112, DAYS - 1)),
            food_effects={Component.CAPSAICIN_SPICE: Effect(2.2, 0.8)},
            high_stress_effect=Effect(1.6, 0.7),
            stress_periods=(StressPeriod("work", "Project deadline", 103, 112),),
            calm_days=frozenset(range(60, 70)),
        ), []
    kacchi = "dish.kacchi_biryani" if "dish.kacchi_biryani" in names else next((m.name for m in menu if m.rich), None)
    forced = {d: (kacchi,) for d in (77, 80, 118)} if kacchi else {}
    return SimConfig(
        days=DAYS, seed=27,
        flare_windows=((41, 53), (83, 92)),
        food_effects={Component.FAT: Effect(2.4, 0.8)},
        late_night_effect=Effect(1.9, 0.75),
        period_effects={"exam": Effect(1.1, 0.7, next_day=0.0)},
        stress_periods=(StressPeriod("exam", "Mid-term exams", 34, 48), StressPeriod("family", "Cousin's wedding week", 76, 81)),
        forced_late_nights=frozenset({76, 78, 81, 117, 119}),
        forced_missed_doses=frozenset({118}),
        forced_foods=forced,
        calm_days=frozenset(range(70, 76)) | frozenset(range(100, 116)),
    ), [("exam", "Final exams", 3, 14)]


def _entry(sim: SimDay, knowledge: MemoryKnowledge) -> DiaryIn:
    foods = []
    for f in sim.foods:
        en, bn = knowledge.names(f.name)
        foods.append(DiaryFood(name=en, name_bn=bn, dish_id=f.name, time_of_day=f.time_of_day, reactions=list(f.reactions)))
    i = sim.items
    return DiaryIn(
        foods=foods,
        stool=Stool(count=i.stools, night_count=i.night_stools, bristol=i.bristol, blood=i.blood, urgency=i.urgency),
        pain=i.pain, wellbeing=i.wellbeing, medication=sim.medication,
        sleep=Sleep(bedtime=sim.bedtime, wake_time=sim.wake_time, quality=sim.sleep_quality), stress=sim.stress,
    )


async def seed_persona(persona: Persona, store: MemoryStore, knowledge: MemoryKnowledge, insights: Insights,
                       flow: MealCheckFlow) -> Patient:
    """(Re)create one test account's sample patient in the in-memory store."""
    store.clear_patient(persona.patient_id)
    insights.forget(persona.patient_id)
    patient = Patient(persona.patient_id, persona.diagnosis, DiseaseState.REMISSION, persona.phenotypes, "bn", is_synthetic=True,
                      display_name=persona.name)
    store.patients[persona.user_id] = patient
    menu = build_menu(knowledge)
    today = insights.today()
    first = today - timedelta(days=DAYS)  # offset 0; offset DAYS-1 is yesterday
    if not menu or persona.history is None:
        return patient
    config, upcoming = _config(persona.history, menu)
    sims = simulate(config, menu)

    bedtimes: list[str] = []
    for sim in sims:
        if not sim.logged:
            continue
        day = first + timedelta(days=sim.offset)
        completed = datetime.combine(day, clock(22, 40), tzinfo=insights.tz)
        entry = build_entry(_entry(sim, knowledge), day, patient.diagnosis, completed, day, bedtimes, True, "")
        await store.save_diary(patient.id, entry)
        bedtimes.append(sim.bedtime)

    for p in config.stress_periods:
        await store.add_stress_period(patient.id, StressPeriodOut(
            id=f"{persona.key}-{p.type}-{p.start}", type=p.type, name=p.name,
            start=first + timedelta(days=p.start), end=first + timedelta(days=p.end)))
    for kind, name, in_days, length in upcoming:
        await store.add_stress_period(patient.id, StressPeriodOut(
            id=f"{persona.key}-{kind}-upcoming", type=kind, name=name,
            start=today + timedelta(days=in_days), end=today + timedelta(days=in_days + length - 1)))

    await _seed_weights(persona, store, sims, config, first)
    await _seed_care(persona, store, today)

    # The patient confirmed the flares the index proposed.
    decisions = await store.period_decisions(patient.id)
    periods = await insights.periods(patient)
    decisions.confirmed |= {date.fromisoformat(p["start"]) for p in periods["periods"] if p["kind"] == "flare"}
    await store.save_period_decisions(patient.id, decisions)

    # Past meal checks for the last few days, made by the real flow (engine verdict, template explanation).
    perceiver = ScriptedPerceiver()
    seeder = MealCheckFlow(knowledge, perceiver, NoExplainer(), flow.scrubber, store, personal=insights.personal_evidence)
    for sim in sims[-6:]:
        day = first + timedelta(days=sim.offset)
        entry = await store.get_diary(patient.id, day)
        if entry is None:
            continue
        for meal, hour in (("noon", 13), ("evening", 20)):
            foods = [f for f in entry.foods if f.time_of_day == meal]
            if not foods:
                continue
            perceiver.items = [f.name for f in foods]
            meal_check_id = None
            async for event in seeder.stream(patient, "en", None, None):
                if event.name == "done":
                    meal_check_id = event.data["meal_check_id"]
            if meal_check_id is None:
                continue
            store.meal_checks[meal_check_id].created_at = datetime.combine(day, clock(hour, 20), tzinfo=insights.tz)
            store.meal_checks[meal_check_id].input_type = "photo" if meal == "evening" else "text"
            for f in foods:
                f.source, f.meal_check_id = "meal_check", meal_check_id
    await insights.personal_evidence(patient)  # warm the cache
    return patient


async def _seed_weights(persona: Persona, store: MemoryStore, sims: list[SimDay], config: SimConfig, first: date) -> None:
    """Weekly sample weigh-ins that follow the simulated history (lower in flares, recovering after)."""
    if persona.history not in WEIGHT_PROFILES:
        return
    usual, flare_rate, period_rate = WEIGHT_PROFILES[persona.history]
    rng = random.Random(f"{persona.key}-weight")
    weight = usual
    for sim in sims:
        stressed = any(p.start <= sim.offset <= p.end for p in config.stress_periods)
        if sim.in_flare:
            weight -= flare_rate
        elif stressed:
            weight -= period_rate
        else:
            weight += (usual - weight) * 0.06
        if (DAYS - sim.offset) % WEIGH_IN_EVERY == 2:  # the last weigh-in is two days ago
            await store.save_weight(persona.patient_id, first + timedelta(days=sim.offset), round(weight + rng.gauss(0, 0.2), 1))


async def _seed_care(persona: Persona, store: MemoryStore, today: date) -> None:
    """Sample medicines and tests; the last two days' doses ticked where that day's diary says "taken"."""
    for i, (name, times, every, started) in enumerate(SAMPLE_MEDICINES.get(persona.history or "", [])):
        await store.save_medication(persona.patient_id, MedicationOut(
            id=f"{persona.key}-med-{i}", name=name, times=times, every_days=every, start=today - timedelta(days=started)))
    for i, (kind, in_days, at) in enumerate(SAMPLE_APPOINTMENTS.get(persona.history or "", [])):
        await store.add_appointment(persona.patient_id, AppointmentOut(
            id=f"{persona.key}-appt-{i}", kind=kind, date=today + timedelta(days=in_days), time=at))
    meds = await store.list_medications(persona.patient_id)
    for back in (1, 2):
        day = today - timedelta(days=back)
        entry = await store.get_diary(persona.patient_id, day)
        if entry is not None and entry.medication == "taken":
            for dose in doses_for(meds, day, set()):
                await store.set_dose(persona.patient_id, day, dose["medication_id"], dose["time"], True)


async def seed_demo(store: MemoryStore, knowledge: MemoryKnowledge, insights: Insights, flow: MealCheckFlow) -> None:
    """Create every test account's sample patient. Called once at start-up."""
    for persona in PERSONAS:
        await seed_persona(persona, store, knowledge, insights, flow)
