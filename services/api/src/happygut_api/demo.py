"""Demo mode: a one-tap demo account with a simulated patient (always labelled "simulated").

The persona is generated by ``happygut_engine.simulate`` with known, injected patterns
(high-fat meals, late nights and exam periods raise symptoms; spice and lactose don't), so
what the Pattern Finder shows in the demo can be checked against the truth. Dates are
relative to today: the history ends yesterday, and tonight's diary is still to fill in.

Everything lives in the in-memory store and is rebuilt on every start.
"""

