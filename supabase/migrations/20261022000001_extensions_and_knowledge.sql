-- HappyGut: extensions and the knowledge schema (food knowledge, Rule Cards, guideline corpus).
-- Knowledge tables hold no patient data.

create schema if not exists extensions;
create extension if not exists vector with schema extensions;
create extension if not exists pg_trgm with schema extensions;

create schema if not exists knowledge;

-- Sources: every citation and its licence. full_text_allowed decides whether chunk text may be stored.
create table knowledge.sources (
  key               text primary key,
  citation          text not null,
  doi               text,
  pmid              text,
  url               text,
  licence           text not null,
  full_text_allowed boolean not null default false,
  retrieved_at      timestamptz,
  created_at        timestamptz not null default now()
);

create table knowledge.dishes (
  id           text primary key check (id like 'dish.%'),
  name_en      text not null,
  name_bn      text not null,
  category     text,
  components   jsonb not null,            -- {"fat": "high", ...}, controlled vocabulary
  alternatives text[] not null default '{}',
  sources      jsonb not null default '[]',
  status       text not null check (status in ('draft', 'approved')),
  updated_at   timestamptz not null default now()
);

-- Every way a dish can be named (English, Bangla, Banglish aliases) for fuzzy resolution.
create table knowledge.dish_names (
  id              bigint generated always as identity primary key,
  dish_id         text not null references knowledge.dishes (id) on delete cascade,
  name            text not null,
  normalized      text not null,          -- lower-cased, NFC, single spaces
  lang            text not null check (lang in ('en', 'bn', 'banglish')),
  embedding       extensions.vector(1024),
  embedding_model text,
  unique (dish_id, normalized)
);
create index dish_names_trgm on knowledge.dish_names using gin (normalized extensions.gin_trgm_ops);

create table knowledge.rule_cards (
  id                text primary key,
  component         text not null,
  min_level         text not null check (min_level in ('low', 'medium', 'high')),
  diagnoses         text[] not null,
  phenotypes        text[] not null default '{}',   -- empty = any
  states            text[] not null,
  severity          smallint not null check (severity between 0 and 3),
  hard              boolean not null default false,
  evidence_level    text not null check (evidence_level in ('guideline', 'trial', 'clinical_practice', 'patient_reported')),
  title_en          text not null,
  title_bn          text not null,
  recommendation_en text not null,
  recommendation_bn text not null,
  sources           jsonb not null,                 -- [{key, citation, doi, pmid, licence, quote}]
  status            text not null check (status in ('draft', 'approved')),
  reviewed_by       text,
  embedding         extensions.vector(1024),
  embedding_model   text,
  updated_at        timestamptz not null default now(),
  check (status = 'draft' or reviewed_by is not null)
);

-- Guideline corpus chunks for contextual hybrid RAG.
create table knowledge.chunks (
  id              text primary key,               -- content hash
  source_key      text not null references knowledge.sources (key),
  section         text,
  text            text not null,
  context_header  text,                           -- generated by GPU job G1
  header_model    text,
  token_count     integer,
  embedding       extensions.vector(1024),        -- generated by GPU job G3 (BGE-M3)
  embedding_model text,
  licence         text not null,
  tsv             tsvector generated always as (
                    to_tsvector('english'::regconfig, coalesce(context_header, '') || ' ' || text)
                  ) stored,
  created_at      timestamptz not null default now()
);
create index chunks_tsv on knowledge.chunks using gin (tsv);
create index chunks_embedding on knowledge.chunks
  using hnsw (embedding extensions.vector_cosine_ops) with (m = 16, ef_construction = 64);
create index chunks_source on knowledge.chunks (source_key);

-- Licence gate: chunk text may only be stored for sources whose licence allows full text.
create function knowledge.enforce_full_text_licence() returns trigger
language plpgsql set search_path = '' as $$
begin
  if not exists (
    select 1 from knowledge.sources s where s.key = new.source_key and s.full_text_allowed
  ) then
    raise exception 'source % does not allow storing full text (use a Rule Card instead)', new.source_key;
  end if;
  return new;
end $$;

create trigger chunks_licence_gate
  before insert or update of text, source_key on knowledge.chunks
  for each row execute function knowledge.enforce_full_text_licence();
